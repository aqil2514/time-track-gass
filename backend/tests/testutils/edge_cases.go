package testutils

import (
	"bytes"
)

// CreateInvalidFormatFile creates a text file for testing invalid format
func CreateInvalidFormatFile() []byte {
	return []byte("This is not an image file, just plain text.")
}

// CreateCorruptedPNG creates a truncated/corrupted PNG header
func CreateCorruptedPNG() []byte {
	// PNG header starts with signature, then IHDR
	// Create partial header that will fail parsing
	return []byte{
		0x89, 0x50, 0x4E, 0x47, 0x0D, 0x0A, 0x1A, 0x0A, // PNG signature
		0x00, 0x00, 0x00, 0x0D, // IHDR length (partial)
		// Missing rest of IHDR chunk - this will fail to parse
	}
}

// CreateTooLargePayload creates a payload that exceeds max size
// Instead of actual huge image, create bytes that exceed limit
func CreateTooLargePayload(sizeBytes int) []byte {
	// Repeat PNG signature to create a large payload
	pngSig := []byte{0x89, 0x50, 0x4E, 0x47, 0x0D, 0x0A, 0x1A, 0x0A}
	return bytes.Repeat(pngSig, (sizeBytes/len(pngSig))+1)
}

// CreateMinimalValidPNG creates a 1x1 pixel valid PNG
func CreateMinimalValidPNG() []byte {
	// Minimal valid 1x1 transparent PNG
	return []byte{
		0x89, 0x50, 0x4E, 0x47, 0x0D, 0x0A, 0x1A, 0x0A, // PNG signature
		0x00, 0x00, 0x00, 0x0D, 0x49, 0x48, 0x44, 0x52, // IHDR chunk
		0x00, 0x00, 0x00, 0x01, // Width: 1
		0x00, 0x00, 0x00, 0x01, // Height: 1
		0x08, 0x06, 0x00, 0x00, 0x00, // Bit depth: 8, Color type: 0 (grayscale), etc.
		0x1F, 0x15, 0xC4, 0x89, // CRC
		0x00, 0x00, 0x00, 0x0A, 0x49, 0x44, 0x41, 0x54, // IDAT chunk
		0x78, 0x9C, 0x63, 0x00, 0x01, 0x00, 0x00, 0x05, // Compressed data
		0x00, 0x01, 0x0D, 0x0A, 0x2D, 0xB4, 0x00, 0x00, 0x00, 0x00, 0x49, 0x45, 0x4E, 0x44, // IEND chunk
		0xAE, 0x42, 0x60, 0x82, // CRC
	}
}

// CreateEmptyFile creates an empty byte slice for testing empty uploads
func CreateEmptyFile() []byte {
	return []byte{}
}

